"""Every real capture ARGUS has been tested on, pooled into one test, plus the event count.

Pooled (real data with ground truth, scored by the same code as tools/eval_lab.py):
  * lab windows with CALDERA labels (cases_lab: run 1, smoke): attack/benign per window,
    attack steps, event precision
  * benign-only lab captures (cases_lab without labels, e.g. the burn-in): every window
    benign; refused if a CALDERA agent's activity is present (as tools/eval_benign.py)
  * the earlier real Linux attack captures (cases_linux): one case each, case-level truth
    from meta.json

Not pooled, counted only: cases_benign (generated by tools/make_benign_cases.py, so not
real), and live runs (live/<run>, not yet graded against labels). The retired CITAR
corpus is out of scope (amendment A1).

Arms: ARGUS's hand-written rules alone, and with the installed learned library.

Usage (from the project root):
  .venv/bin/python tools/eval_cumulative.py --out eval_runs/<date>-cumulative
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "source code"))
sys.path.insert(0, str(ROOT / "tools"))

import lab_common as E                                           # noqa: E402
from eval_benign import _attack_free, _events                    # noqa: E402
from eval_lab import LIBRARY, arms                               # noqa: E402
from argus.case import load_case                                 # noqa: E402


def _lines(p: Path) -> int:
    with open(p, "rb") as fh:
        return sum(1 for _ in fh)


def counts() -> dict:
    """Events (lab windows, live) and claims (raw-log cases) per corpus."""
    out = {}
    by = Counter()
    for w in E.windows():
        by[E.operation(w)] += _lines(w / "events.jsonl")
    out["lab_windows"] = dict(by)
    live = ROOT / "live"
    out["live"] = {r.name: sum(_lines(c / "events.jsonl") for c in r.iterdir() if (c / "events.jsonl").exists())
                   for r in sorted(live.iterdir()) if r.is_dir()} if live.is_dir() else {}   # runs, not their logs
    for corpus in ("cases_linux", "cases_benign"):
        d = ROOT / corpus
        out[corpus] = sum(len(load_case(c).claims) for c in sorted(d.iterdir()) if c.is_dir()) if d.is_dir() else 0
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--library", type=Path, default=LIBRARY)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    wins = E.windows()
    labelled = [w for w in wins if (w / "labels.json").exists()]
    benign_only = [w for w in wins if not (w / "labels.json").exists()]
    dirty = [w.name for w in benign_only if not _attack_free(w, _events(w))]
    if dirty:
        sys.exit(f"unlabelled windows with agent activity cannot count as benign: {dirty[:5]}")
    older = sorted(c for c in (ROOT / "cases_linux").iterdir() if c.is_dir()) if (ROOT / "cases_linux").is_dir() else []

    fz = E.freeze_status()
    n = counts()
    total_events = sum(n["lab_windows"].values()) + sum(n["live"].values())
    print(f"ARGUS freeze {fz['manifest']} matches={fz['matches']}")
    print(f"events: lab windows {n['lab_windows']}, live {n['live']}; "
          f"claims: cases_linux {n['cases_linux']}, cases_benign (synthetic) {n['cases_benign']}")
    out = {"freeze": fz, "counts": n, "total_events_lab_and_live": total_events, "arms": {}}

    for arm, cfg in arms(args.library).items():
        att = ben = att_f = ben_f = ben_gate = ben_gate_f = 0
        steps = steps_d = sel = mal = 0
        per_op: dict[str, Counter] = {}
        for w in labelled + benign_only:
            r = E.score_window(w, cfg)
            flagged = r["disposition"] in E.FLAGGED
            op = E.operation(w)
            c = per_op.setdefault(op, Counter())
            if w in labelled:
                lab = E.labels(w)
                ev = set().union(*[a["events"] for a in r["alerts"].values()]) if r["alerts"] else set()
                m = set(lab["malicious_event_ids"])
                sel += len(ev)
                mal += len(ev & m)
                for a in lab.get("abilities", []):
                    steps += 1
                    steps_d += bool(ev & set(a["event_ids"]))
                    c["steps"] += 1
                    c["steps_detected"] += bool(ev & set(a["event_ids"]))
                attack = lab["category"] == "attack"
            else:
                attack = False
            gate = E.meta(w).get("capture_gate", "pass") == "pass"
            if attack:
                att += 1
                att_f += flagged
                c["attack"] += 1
                c["attack_flagged"] += flagged
            else:
                ben += 1
                ben_f += flagged
                ben_gate += gate
                ben_gate_f += flagged and gate
                c["benign"] += 1
                c["benign_flagged"] += flagged
        old_f = 0
        for case in older:
            lc = load_case(case)
            from argus.reason.engine import reason
            d = reason(lc.case_id, lc.claims, lc.health, cfg, lc.protocol_artifacts)
            old_f += d.disposition.value in E.FLAGGED
        m = {"lab_windows": len(labelled) + len(benign_only),
             "attack_windows_flagged": f"{att_f}/{att}", "benign_windows_flagged": f"{ben_f}/{ben}",
             "benign_clean_windows_flagged": f"{ben_gate_f}/{ben_gate}",
             "benign_per_20_host_windows": round(20 * ben_f / ben, 2) if ben else None,
             "attack_steps_detected": f"{steps_d}/{steps}", "step_recall_ci95": E.wilson(steps_d, steps),
             "event_precision": round(mal / sel, 4) if sel else None,
             "earlier_attack_captures_flagged": f"{old_f}/{len(older)}",
             "attack_units_flagged_all": f"{att_f + old_f}/{att + len(older)}",
             "per_capture": {k: dict(v) for k, v in per_op.items()}}
        out["arms"][arm] = m
        print(f"\n[{arm}]")
        for k, v in m.items():
            if k != "per_capture":
                print(f"  {k}: {v}")
        for op, v in m["per_capture"].items():
            print(f"    {op}: {dict(v)}")
    if args.out:
        args.out.mkdir(parents=True, exist_ok=True)
        (args.out / "summary.json").write_text(json.dumps(out, indent=1, default=sorted))
        print(f"\nwrote {args.out}/summary.json")


if __name__ == "__main__":
    main()
